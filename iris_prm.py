def extract_obstacle_rectangles(obstacle_map):
    """
    Detects each separate black obstacle rectangle.
    Returns a list of (x_min, x_max, y_min, y_max).
    """

    import cv2
    import numpy as np

    # Ensure binary: obstacles = 0, free = 255
    _, thresh = cv2.threshold(obstacle_map, 127, 255, cv2.THRESH_BINARY_INV)

    # Find connected components
    num_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(thresh)

    rectangles = []

    # stats: [label][x, y, width, height, area]
    # skip label 0 → background
    for i in range(1, num_labels):
        x = int(stats[i][0])
        y = int(stats[i][1])
        w = int(stats[i][2])
        h = int(stats[i][3])

        x_min = x
        x_max = x + w
        y_min = y
        y_max = y + h

        rectangles.append((x_min, x_max, y_min, y_max))

    return rectangles
def build_prm_and_plan(start_xy, goal_xy, num_nodes=200, k=10):
    # 1) Load obstacle image  -> obstacle_map (uint8 array)
    url = "https://github.com/asu-iris/course_robotics/raw/main/lec6-mp/figures/Obstacle.png"
    response = requests.get(url)
    original_image = Image.open(BytesIO(response.content)).convert('L')
    obstacle_map = np.array(original_image)

    # 2) Build PRM (use your existing helpers)
    nodes = generate_random_nodes(num_nodes, obstacle_map)
    nodes = filter_nodes(nodes, obstacle_map)
    link_nodes(nodes, k, obstacle_map)

    # 3) Add start & goal nodes
    start_node = Node(*start_xy)
    goal_node  = Node(*goal_xy)
    nodes.extend([start_node, goal_node])
    link_nodes(nodes, k, obstacle_map)

    # 4) Plan with A*
    path = a_star(start_node, goal_node, nodes)

    return path, obstacle_map


def pixel_to_world(node, obstacle_map, world_w=4.0, world_h=4.0):
    """Map image pixels to MuJoCo world (meters) on a 4m x 4m floor."""
    h, w = obstacle_map.shape
    x_m = (node.x / w - 0.5) * world_w
    y_m = (node.y / h - 0.5) * world_h
    return x_m, y_m

