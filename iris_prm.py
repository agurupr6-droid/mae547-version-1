# define note class in the road map
class Node:
    def __init__(self, x, y):
        self.x = x
        self.y = y
        self.edges = []

    def add_edge(self, node):
        self.edges.append(node)

    def __lt__(self, other):
        return (self.x, self.y) < (other.x, other.y)

    def __hash__(self):
        return hash((self.x, self.y))

    def __eq__(self, other):
        return (self.x, self.y) == (other.x, other.y)

# define the distance between two notes
def distance(node1, node2):
    return math.sqrt((node1.x - node2.x)**2 + (node1.y - node2.y)**2)

# is node in the obstacles
def node_in_obstacle(node, obstacle_map):
    return obstacle_map[int(node.y), int(node.x)] == 0

# is the link between note1 and note2 passing obstacles
def link_in_obstacle(node1, node2, obstacle_map):
    line_x= np.linspace(node1.x, node2.x, 10)
    line_y= np.linspace(node1.y, node2.y, 10)
    for x, y in zip(line_x, line_y):
        if obstacle_map[int(y), int(x)] ==0:
            return True
    return False

# genearte random node on a obstacle map
def generate_random_nodes(num_nodes, obstacle_map):
    x_max, y_max = obstacle_map.shape[1], obstacle_map.shape[0]
    nodes = []
    while len(nodes) < num_nodes:
        x = random.uniform(0, x_max)
        y = random.uniform(0, y_max)
        node = Node(x, y)
        nodes.append(Node(x, y))
    return nodes

# remove random node on obstacles
def filter_nodes(nodes, obstacle_map):
    filtered_nodes = []
    for node in nodes:
        if not node_in_obstacle(node, obstacle_map):
            filtered_nodes.append(node)
    return filtered_nodes


# link two neighbour nodes on a obstacle map using  k-nearest search
def link_nodes(nodes, k, obstacle_map):
    for node in nodes:
        distances = []
        for other_node in nodes:
            if node != other_node and not link_in_obstacle(node, other_node, obstacle_map):
                distances.append((distance(node, other_node), other_node))
        distances.sort(key=lambda x: x[0])

        for d, other_node in distances[:k]:
            node.add_edge(other_node)
            other_node.add_edge(node)

# implementation of a star search algorithm
def a_star(start_node, goal_node, nodes):
    open_list = []
    heapq.heappush(open_list, (0, start_node))
    came_from = {}

    # cost-so-far
    g_score = {node: float('inf') for node in nodes}
    g_score[start_node] = 0

    # total cost: cost-so-far + estimated cost-to-go
    f_score = {node: float('inf') for node in nodes}
    f_score[start_node] = distance(start_node, goal_node)

    while open_list:

        # pop up the first note to expand the tree
        _, current_node = heapq.heappop(open_list)

        if current_node == goal_node:
            path = []
            while current_node in came_from:
                path.append(current_node)
                current_node = came_from[current_node]
            path.append(start_node)
            return path[::-1]

        for neighbor_node in current_node.edges:
            tentative_g_score = g_score[current_node] + distance(current_node, neighbor_node)
            if tentative_g_score < g_score[neighbor_node]:
                came_from[neighbor_node] = current_node
                g_score[neighbor_node] = tentative_g_score
                f_score[neighbor_node] = tentative_g_score + distance(neighbor_node, goal_node)
                heapq.heappush(open_list, (f_score[neighbor_node], neighbor_node))

    return None


